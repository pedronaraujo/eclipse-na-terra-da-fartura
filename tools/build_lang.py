def nest(lang):
    out = {}
    for k, v in T.items():
        cur = out.setdefault('ECLIPSE', {})
        parts = k.split('.')
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
        cur[parts[-1]] = v[0 if lang == 'pt-BR' else 1]
    return out


os.makedirs(f'{ROOT}/lang', exist_ok=True)
for lang in ('pt-BR', 'en'):
    with open(f'{ROOT}/lang/{lang}.json', 'w', encoding='utf-8') as fh:
        json.dump(nest(lang), fh, ensure_ascii=False, indent=2)
print('lang ok', len(T))
